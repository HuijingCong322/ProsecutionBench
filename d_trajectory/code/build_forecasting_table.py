"""Fill the paper's appendix table `tab:forecasting` (Trajectory Forecasting: Disposition, Remaining Rounds,
Time to Next Action) from metrics/D/trajectory_metrics.csv and metrics/D/rounds_next_metrics.csv.

Usage: python build_forecasting_table.py --root path/to/D_trajectory
Writes results/forecasting_table.csv (all numbers + 95% intervals) and results/forecasting_table.tex
(rows that have no result yet show n/a, never 0.00).
"""
import argparse, os
import pandas as pd

ROWS = [  # (label in the paper, method, model substring, input_setting)
    ("Marginal (no covariates)", "km", None, None),
    ("Cox proportional hazards", "cox_ph_cutoff_features", None, None),
    ("GPT-5-mini, history only", "llm_history_only", "gpt-5-mini", "history_only"),
    ("GPT-5-mini, state with history", "llm_state_with_history", "gpt-5-mini", "state_with_history"),
    ("Qwen3.6-27B, history only", "llm_history_only", "qwen", "history_only"),
    ("Qwen3.6-27B, state with history", "llm_state_with_history", "qwen", "state_with_history"),
]


def pick(df, method, model, setting):
    if df is None or not len(df):
        return None
    m = df.method.str.startswith(method) if method == "km" else (df.method == method)
    if model:
        m &= df.model.fillna("").str.lower().str.contains(model)
    if setting:
        m &= df.input_setting == setting
    m &= ~df.model.fillna("").str.contains("mock")
    s = df[m]
    return s.iloc[0] if len(s) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    a = ap.parse_args()
    R = a.root
    rd = lambda f: pd.read_csv(os.path.join(R, "metrics", "D", f)) if os.path.exists(os.path.join(R, "metrics", "D", f)) else None
    T, N = rd("trajectory_metrics.csv"), rd("rounds_next_metrics.csv")
    out = []
    for label, method, model, setting in ROWS:
        t, n = pick(T, method, model, setting), pick(N, method, model, setting)
        out.append(dict(
            approach=label,
            disp_c_index=None if t is None else t.c_index, disp_ibs=None if t is None else t.ibs,
            disp_brier_12m=None if t is None else t.brier_12m, disp_brier_24m=None if t is None else t.brier_24m,
            rounds_mae=None if n is None else n.rounds_mae, rounds_mae_ci=None if n is None else f"[{n.rounds_mae_lo:.2f}, {n.rounds_mae_hi:.2f}]",
            rounds_acc=None if n is None else n.rounds_acc, rounds_acc_ci=None if n is None else f"[{n.rounds_acc_lo:.2f}, {n.rounds_acc_hi:.2f}]",
            next_c_index=None if n is None else n.next_c_index,
            next_c_ci=None if n is None or pd.isna(n.next_c_lo) else f"[{n.next_c_lo:.2f}, {n.next_c_hi:.2f}]",
            next_mae_days=None if n is None else n.next_mae_days,
            next_mae_ci=None if n is None else f"[{n.next_mae_lo:.1f}, {n.next_mae_hi:.1f}]",
            rounds_scored=None if n is None else n.rounds_scored, next_scored=None if n is None else n.next_scored))
    D = pd.DataFrame(out)
    os.makedirs(os.path.join(R, "results"), exist_ok=True)
    D.to_csv(os.path.join(R, "results", "forecasting_table.csv"), index=False)

    f2 = lambda v: "\\na" if v is None or pd.isna(v) else f"{v:.2f}"
    f1 = lambda v: "\\na" if v is None or pd.isna(v) else f"{v:.1f}"
    lines = [r"% generated by code/build_forecasting_table.py -- test_core (100 cases), cutoff = A1 filing date",
             r"\begin{tabular}{@{}l cccc cc cc@{}}", r"\toprule",
             r"& \multicolumn{4}{c}{\tcat{googlepurple}{Disposition}} & \multicolumn{2}{c}{\tcat{googlepurple}{Remaining Rounds}} & \multicolumn{2}{c}{\tcat{googlepurple}{Time to Next Action}} \\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
             r"\textbf{Approach} & C-index & IBS$\downarrow$ & Brier@12$\downarrow$ & Brier@24$\downarrow$ & MAE$\downarrow$ & Acc. & C-index & MAE (days)$\downarrow$ \\",
             r"\midrule", r"\multicolumn{9}{@{}l}{\textit{Without language models}} \\"]
    for i, r in D.iterrows():
        if i == 2:
            lines += [r"\midrule", r"\multicolumn{9}{@{}l}{\textit{Language models}} \\"]
        lines.append(f"{r.approach} & {f2(r.disp_c_index)} & {f2(r.disp_ibs)} & {f2(r.disp_brier_12m)} & {f2(r.disp_brier_24m)} & "
                     f"{f2(r.rounds_mae)} & {f2(r.rounds_acc)} & {f2(r.next_c_index)} & {f1(r.next_mae_days)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    open(os.path.join(R, "results", "forecasting_table.tex"), "w").write("\n".join(lines) + "\n")
    with pd.option_context("display.width", 250, "display.max_columns", 30):
        print(D.drop(columns=["rounds_scored", "next_scored"]).round(3).to_string(index=False))


if __name__ == "__main__":
    main()
