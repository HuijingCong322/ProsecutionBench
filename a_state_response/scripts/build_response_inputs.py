"""Build Applicant Response inputs (A, week 3) from data_v1_share.
Usage: python3 A/scripts/build_response_inputs.py
Samples: the 10 gold_subset apps (scored: Strat, Edit, Supp) + 3 dev apps (smoke test) + the other 90 test_core apps
(supplementary Strat against automatic labels, data_v1 update plan). test_core apps have no predicted O1 state
(state tracking ran at the A1 cutoff for them), so their input says so: a different input setting from gold.
Task: given the record as of the first Office action (O1), propose the applicant's reply (A1).
Visible documents: the example's inputs dated on or before the O1 mail date (nothing from A1 or later).
The description is included (needed for claim support); when both the filed specification and the
PGPUB description are visible, only the filed specification is kept. Long descriptions are truncated
at MAX_DESC characters (recorded in truncated_doc_ids).
Each input also carries the PREDICTED O1 state (frozen state-tracking prompt p3/low, A/outputs/state_predictions.jsonl;
dev: outputs/variants/p3_low, same prompt and effort), rendered compactly (claim status/version, rejections by ground).
Cited prior-art full texts are not in the record; this is stated in the input and in missing_prior_art.
Output: A/inputs/response_inputs.jsonl."""
import hashlib, json, re
from pathlib import Path
A = Path(__file__).resolve().parent.parent; S = A.parent / "data_v1_share"
MAX_DESC = 120_000
import csv
labels = list(csv.DictReader(open(S / "labels.csv")))
core = [r["app_id"] for r in labels if r["test_core"] == "True"]
gold = {r["app_id"] for r in labels if r["gold_subset"] == "True"}
DEV = ["11968167", "11968173", "11968176"]

def render(x):
    p = S / x["text_path"]
    if not x["text_path"] or not p.exists(): return None
    if p.suffix == ".json":
        return "\n".join(f"{c['number']}. " + re.sub(r"^\s*\d{1,3}\s*[.)]\s*", "", c["text"]) for c in json.loads(p.read_text()))
    return p.read_text()

from collections import defaultdict
def ranges(ns):
    ns = sorted(set(ns)); out = []
    for n in ns:
        if out and n == out[-1][1] + 1: out[-1][1] = n
        else: out.append([n, n])
    return ", ".join(f"{a}" if a == b else f"{a}-{b}" for a, b in out)
pstate = {}
for f in (A / "outputs" / "state_predictions.jsonl", A / "outputs" / "variants" / "p3_low" / "state_predictions.jsonl"):
    for x in map(json.loads, open(f)):
        if x["stage"] == "O1_cutoff" and x.get("parse_ok") and x["app_id"] not in pstate: pstate[x["app_id"]] = x
def render_state(x):
    st = x["state"]; by = defaultdict(list); rj = defaultdict(list)
    for c in st.get("entered_claims") or []:
        try: by[(c.get("status"), c.get("version_id"))].append(int(c["claim_id"]))
        except (TypeError, ValueError, KeyError): pass
    for r in st.get("rejections") or []:
        try: rj[(r.get("ground"), r.get("status"))].append(int(r["claim_id"]))
        except (TypeError, ValueError, KeyError): pass
    lines = ["=== PREDICTED STATE at the O1 mail date (model-generated by the state-tracking step; may contain errors) ===",
             "Claims under examination (status [version_id]):"]
    lines += [f"  {ranges(v)}: {s} [{ver}]" for (s, ver), v in sorted(by.items(), key=lambda kv: min(kv[1]))]
    lines.append("Rejections / objections (ground, status: claims):")
    lines += [f"  {g}, {s}: {ranges(v)}" for (g, s), v in sorted(rj.items(), key=lambda kv: str(kv[0]))]
    return "\n".join(lines)
PRIOR = ("=== PRIOR ART ===\nFull texts of the references cited by the examiner are NOT included in this record; only the examiner's "
         "characterization of them in the Office action is available. Do not treat that characterization as verified technical content.")
out = open(A / "inputs" / "response_inputs.jsonl", "w"); n = 0
NOSTATE = "=== PREDICTED STATE ===\nNot available for this application (input setting: record only)."
for app, group in [(a, "dev") for a in DEV] + [(a, "gold" if a in gold else "test_core") for a in core]:
    e = json.loads((S / "examples" / f"{app}.json").read_text())
    cut = e["o1"]["mail_date"]
    vis = [x for x in e["inputs"] if x["date"] <= cut and x.get("role") != "A1"]
    has_spec = any(x["doc_code"] == "SPEC" and x["doc_id"] != "pgpub_description" for x in vis)
    parts, ids, missing, trunc, dropped = [], [], [], [], []
    for x in vis:
        if x["doc_id"] == "pgpub_description" and has_spec: dropped.append(x["doc_id"]); continue
        t = render(x)
        if t is None: missing.append(x["doc_id"]); continue
        if x["doc_code"] == "SPEC" and len(t) > MAX_DESC: t = t[:MAX_DESC] + "\n[... description truncated ...]"; trunc.append(x["doc_id"])
        ids.append(x["doc_id"])
        parts.append(f"=== DOC {x['doc_id']} | {x['doc_code']} | {x['date']} | role={x['role']} | text_source={x['source']} ===\n{t.strip()}")
    if group != "test_core" and app not in pstate: raise SystemExit(f"no predicted O1 state for {app}")
    st = pstate.get(app) if group != "test_core" else None
    text = "\n\n".join(parts + [render_state(st) if st else NOSTATE, PRIOR])
    row = {"input_setting": "record+predicted_state" if st else "record_only",
           "state_input_hash": st["input_hash"] if st else None, "state_prompt_hash": st["prompt_hash"] if st else None, "missing_prior_art": True,"sample_id": f"{app}_t1", "app_id": app, "group": group, "cutoff": cut, "o1_doc_id": e["o1"]["doc_id"],
           "o1_code": e["o1"]["code"], "doc_ids": ids, "dropped_doc_ids": dropped, "missing_doc_ids": missing,
           "truncated_doc_ids": trunc, "input_hash": hashlib.sha1(text.encode()).hexdigest()[:16],
           "approx_tokens": len(text) // 4, "input_text": text}
    out.write(json.dumps(row) + "\n"); n += 1
out.close()
rows = [json.loads(l) for l in open(A / "inputs" / "response_inputs.jsonl")]
from collections import Counter
tok = sorted(r["approx_tokens"] for r in rows)
print("rows", n, Counter(r["group"] for r in rows), "| tokens p50/p90/max", tok[len(tok)//2], tok[int(len(tok)*.9)], tok[-1],
      "| truncated", sum(bool(r["truncated_doc_ids"]) for r in rows), "| missing", sum(bool(r["missing_doc_ids"]) for r in rows))
# leakage check: no visible doc dated after O1
for r in rows:
    e = json.loads((S / "examples" / f"{r['app_id']}.json").read_text())
    dates = {x["doc_id"]: x["date"] for x in e["inputs"]}
    assert all(dates[d] <= r["cutoff"] for d in r["doc_ids"]), r["app_id"]
print("leakage check ok")
